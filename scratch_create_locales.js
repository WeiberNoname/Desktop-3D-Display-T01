const masterEN = newTranslations["en"];
let count = 0;
Object.keys(newTranslations).forEach(code => {
  const dir = path.join(__dirname, 'locales', code);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  const filePath = path.join(dir, 'translation.json');
  // Fallback merge: guarantee all master English keys exist in every language dictionary
  const merged = Object.assign({}, masterEN, newTranslations[code] || {});
  fs.writeFileSync(filePath, JSON.stringify(merged, null, 2) + '\n', 'utf8');
  count++;
  console.log(`[${count}/31] Created translation file: ${filePath} (Keys: ${Object.keys(merged).length})`);
});

